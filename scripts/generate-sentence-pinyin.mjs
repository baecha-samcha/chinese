// Drafts pinyin for sentences that don't have any yet, as reviewable SQL.
//   node scripts/generate-sentence-pinyin.mjs <sentences.json> <vocabulary.json> > scripts/data/sentence-pinyin.sql
// (both files are the /api/sentences and /api/vocabulary responses, or the
// matching arrays from an /api/export backup).
// Each sentence is converted token by token: a token that is a registered
// vocabulary word with a single known pinyin reuses that curated pinyin;
// anything else falls back to pinyin-pro's dictionary (tone sandhi on, to
// match the course data, e.g. 一下 yíxià, 不是 búshì). Sentences with a
// guess that deserves a human look are tagged `-- REVIEW:` with the reason.
// UPDATEs only fill rows whose pinyin is still empty, so re-running never
// overwrites a manual correction.
import { readFile } from "node:fs/promises";
import { pinyin, polyphonic } from "pinyin-pro";
const [sentencesPath, vocabularyPath] = process.argv.slice(2);
if (!sentencesPath || !vocabularyPath) {
  console.error("usage: generate-sentence-pinyin.mjs <sentences.json> <vocabulary.json>");
  process.exit(1);
}
const sentences = JSON.parse(await readFile(sentencesPath, "utf8"));
const vocabulary = JSON.parse(await readFile(vocabularyPath, "utf8"));
const known = new Map();
for (const v of vocabulary) {
  const set = known.get(v.simplified) || new Set();
  set.add(v.pinyin.trim().normalize("NFC"));
  known.set(v.simplified, set);
}
const punctuation = { "。": ".", "？": "?", "！": "!", "，": ",", "、": ",", "：": ":", "；": ";", "…": "…" };
const han = /\p{Script=Han}/u;
// Dictionary-polyphonic characters whose other readings never occur in this
// course's sentences; flagging them would only bury the real review items.
const rarelyAmbiguous = new Set("六");
// Course-specific corrections a dictionary can't know: personal names
// (capitalized, surname split from given name) and neutral-tone set phrases.
const fixups = [
  ["jīn dà hán", "Jīn Dàhán"],
  ["jīndàhán", "Jīn Dàhán"],
  ["xìng jīn", "xìng Jīn"],
  ["wáng dōng", "Wáng Dōng"],
  ["jīng jīng", "Jīngjing"],
  ["nǎ lǐ", "nǎli"],
];
const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
const out = ["-- Draft sentence pinyin generated by scripts/generate-sentence-pinyin.mjs.", "-- Review the -- REVIEW: lines, then: npx wrangler d1 execute ch-study --remote --file=scripts/data/sentence-pinyin.sql"];
let reviewCount = 0;
for (const s of sentences) {
  if (s.pinyin) continue;
  const reasons = new Set(), words = [];
  // Walk the original sentence alongside its tokens so punctuation between
  // tokens (没有，我…) survives into the pinyin.
  let pos = 0;
  const chinese = s.chinese.trim();
  const flush = (upTo) => {
    for (const c of chinese.slice(pos, upTo))
      if (punctuation[c] && words.length) words[words.length - 1] += punctuation[c];
  };
  s.tokens.forEach((token, t) => {
    const at = chinese.indexOf(token, pos);
    if (at >= 0) {
      flush(at);
      pos = at + token.length;
    }
    const text = [...token].filter((c) => !punctuation[c]).join("");
    if (!text) return;
    if (!han.test(text)) return words.push(text);
    // Standalone erhua 儿 attaches to the previous syllable (事 儿 → shìr).
    if (text === "儿" && words.length) return (words[words.length - 1] += "r");
    // 一/不 change tone with the following syllable, which only the whole
    // phrase can tell, so read them together with the next token.
    if (text === "一" || text === "不") {
      const next = s.tokens[t + 1] || "";
      words.push(pinyin(text + next, { type: "array", toneSandhi: true })[0]);
      return;
    }
    const readings = [...(known.get(text) || [])];
    // Proper nouns appear both as Zhōngguó and zhōngguó; prefer the capital.
    const distinct = [...new Set(readings.map((r) => r.toLowerCase()))];
    if (distinct.length === 1)
      return words.push((readings.find((r) => r !== r.toLowerCase()) || readings[0]).replace(/\s+/g, ""));
    if (distinct.length > 1) reasons.add(`${text}: 단어장 병음 ${readings.join("/")}`);
    const guess = pinyin(text, { type: "array", toneSandhi: true });
    [...text].forEach((c, i) => {
      if (/[一不]/.test(c) && text.length > 1) reasons.add(`${c} 성조 변화`);
      else if (!rarelyAmbiguous.has(c) && polyphonic(c, { type: "array" })[0]?.length > 1)
        reasons.add(`${c} 다음자(${guess[i]})`);
    });
    let reading = guess.join("");
    if (text.length > 1 && text.endsWith("儿")) reading = reading.replace(/ér$/, "r");
    words.push(reading);
  });
  flush(chinese.length);
  let text = words.join(" ");
  for (const [from, to] of fixups) text = text.replaceAll(from, to);
  text = text.replace(/(^|[.?!] )(\p{L})/gu, (_, lead, c) => lead + c.toUpperCase());
  if (reasons.size) {
    out.push(`-- REVIEW: ${s.chinese} → ${[...reasons].join("; ")}`);
    reviewCount++;
  }
  out.push(`UPDATE sentences SET pinyin=${quote(text)} WHERE chinese=${quote(s.chinese)} AND pinyin='';`);
}
out.push(`-- ${reviewCount} sentence(s) flagged for review.`);
console.log(out.join("\n"));
