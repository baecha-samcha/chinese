// Offline support: the learning app shell is precached on install and every
// static GET is served network-first (fresh when online, cached copy when the
// network fails or stalls). /api and /admin are never cached - study data is
// already cached in localStorage by api.js, and admin needs the server.
const CACHE = "ch-shell-v4-ui-system";
const NETWORK_TIMEOUT_MS = 4000;
const SHELL = [
  "/",
  "/css/style.css",
  "/css/exam.css",
  "/data/exam-scope.json",
  "/js/exam/blueprint.js",
  "/js/exam/bank.js",
  "/js/exam/validation.js",
  "/js/exam/engine.js",
  "/js/exam/ui.js",
  "/vendor/fonts/hanamin/hanamin-fallback.css",
  "/js/app.js",
  "/js/api.js",
  "/js/utils.js",
  "/js/ui.js",
  "/js/learning-ui.js",
  "/js/match-ui.js",
  "/js/match.js",
  "/js/study.js",
  "/js/validation.js",
  "/js/pinyin.js",
  "/js/quiz.js",
  "/js/speech.js",
  "/manifest.webmanifest",
  "/icons/icon.svg",
  "/icons/icon-192.png",
  "/icons/apple-touch-icon.png",
];

// The rare-character font chunks are generated by scripts/vendor.mjs, so read
// their URLs from the generated stylesheet instead of hard-coding them.
async function fontUrls(cache) {
  const css = await cache.match("/vendor/fonts/hanamin/hanamin-fallback.css");
  if (!css) return [];
  return [...(await css.text()).matchAll(/url\("([^"]+)"\)/g)].map((m) => m[1]);
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await cache.addAll(SHELL.map((url) => new Request(url, { cache: "reload" })));
      await cache.addAll(await fontUrls(cache));
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys())
        if (key !== CACHE) await caches.delete(key);
      await self.clients.claim();
    })(),
  );
});

async function networkFirst(request, cacheKey) {
  const cache = await caches.open(CACHE);
  const network = fetch(request).then((response) => {
    if (response.ok) cache.put(cacheKey, response.clone());
    return response;
  });
  const cached = await cache.match(cacheKey);
  if (!cached) return network;
  const timeout = new Promise((resolve) =>
    setTimeout(() => resolve(cached), NETWORK_TIMEOUT_MS),
  );
  return Promise.race([network.catch(() => cached), timeout]);
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (
    request.method !== "GET" ||
    url.origin !== location.origin ||
    url.pathname.startsWith("/api/") ||
    url.pathname === "/admin" ||
    url.pathname.startsWith("/admin/")
  )
    return;
  // Every SPA route is the same index.html, so cache navigations under "/".
  const cacheKey = request.mode === "navigate" ? "/" : url.pathname;
  event.respondWith(networkFirst(request, cacheKey));
});
